async def get_portfolio_shadow_analysis(user_id: str, positions: List[Dict]) -> Dict[str, Any]:
    """
    Main entry point for shadow market analysis.
    
    Returns complete cross-asset correlation analysis for a user's portfolio.
    """
    engine = get_shadow_engine()
    
    # Ensure monitoring is running
    if not engine._running:
        await engine.start_monitoring()
        # Wait a moment for initial data
        await asyncio.sleep(2)
    
    # Run analysis
    analysis = await engine.analyze_portfolio_exposure(user_id, positions)
    
    # Format for API response
    return {
        "shadow_beta": analysis.shadow_beta,
        "diversification_score": analysis.diversification_score,
        "macro_states": {
            driver.value: {
                "current_value": round(state.current_value, 2),
                "change_1h_pct": round(state.change_pct_1h, 2),
                "change_24h_pct": round(state.change_pct_24h, 2),
                "trend": state.trend,
                "volatility": state.volatility
            }
            for driver, state in analysis.macro_states.items()
        },
        "portfolio_exposures": [
            {
                "symbol": exp.symbol,
                "driver": exp.driver.value,
                "correlation": round(exp.correlation_coefficient, 2),
                "expected_impact_pct": round(exp.expected_price_impact_pct, 2),
                "time_to_impact_minutes": exp.typical_impact_lag_minutes,
                "confidence": round(exp.confidence, 1),
                "reasoning": exp.reasoning
            }
            for exp in analysis.portfolio_exposures
        ],
        "active_shadow_alerts": [
            {
                "id": alert.id,
                "severity": alert.severity.value,
                "driver": alert.driver.value,
                "affected_symbols": alert.affected_symbols,
                "trigger": alert.trigger_condition,
                "expected_impact": alert.expected_impact,
                "reasoning": alert.reasoning,
                "recommended_action": alert.recommended_action,
                "eta_to_impact": alert.eta_to_impact,
                "historical_precedent": alert.historical_precedent,
                "timestamp": alert.timestamp.isoformat()
            }
            for alert in analysis.active_alerts
        ],
        "invisible_strings": [
            {
                "from_driver": exp.driver.value,
                "to_symbol": exp.symbol,
                "strength": abs(exp.correlation_coefficient),
                "direction": "negative" if exp.correlation_coefficient < 0 else "positive",
                "description": f"{exp.driver.value.upper()} → {exp.symbol.replace('.NS', '')}: {exp.reasoning[:60]}..."
            }
            for exp in sorted(analysis.portfolio_exposures, 
                            key=lambda x: abs(x.correlation_coefficient), 
                            reverse=True)[:10]
        ],
        "last_update": analysis.last_update.isoformat()
    }
