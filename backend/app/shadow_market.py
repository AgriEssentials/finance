class GlobalDriver(Enum):
    """Global macro drivers that impact Indian markets"""
    DXY = "dxy"  # US Dollar Index
    US10Y = "us10y"  # US 10-Year Treasury
    BRENT_OIL = "brent_oil"  # Brent Crude
    GOLD = "gold"  # Gold prices
    BTC = "btc"  # Bitcoin (risk sentiment)
    VIX = "vix"  # US Volatility Index
    DOW_JONES = "dow_jones"  # Dow Jones
    NASDAQ = "nasdaq"  # NASDAQ (tech proxy)
    SHANGHAI_COMPOSITE = "shanghai"  # China markets
    SGX_NIFTY = "sgx_nifty"  # Singapore NIFTY (pre-market indicator)


class CorrelationStrength(Enum):
    """Strength of correlation"""
    STRONG_NEGATIVE = -3  # -0.8 to -1.0
    MODERATE_NEGATIVE = -2  # -0.6 to -0.8
    WEAK_NEGATIVE = -1  # -0.3 to -0.6
    NONE = 0  # -0.3 to 0.3
    WEAK_POSITIVE = 1  # 0.3 to 0.6
    MODERATE_POSITIVE = 2  # 0.6 to 0.8
    STRONG_POSITIVE = 3  # 0.8 to 1.0


class AlertSeverity(Enum):
    """Alert severity levels"""
    INFO = "info"
    WARNING = "warning"
    RED_ALERT = "red_alert"  # Immediate action needed
    CRITICAL = "critical"  # Portfolio at risk


@dataclass
class MacroDriverState:
    """Current state of a global macro driver"""
    driver: GlobalDriver
    current_value: float
    change_pct_1h: float
    change_pct_24h: float
    trend: str  # spiking, dropping, stable
    volatility: str  # low, normal, high
    last_update: datetime


@dataclass
class CorrelationImpact:
    """Impact of a macro driver on a specific stock/sector"""
    driver: GlobalDriver
    symbol: str
    correlation_coefficient: float
    typical_impact_lag_minutes: int
    expected_price_impact_pct: float
    confidence: float
    historical_accuracy: float
    reasoning: str


@dataclass
class ShadowAlert:
    """Alert generated by shadow market analysis"""
    id: str
    severity: AlertSeverity
    driver: GlobalDriver
    affected_symbols: List[str]
    trigger_condition: str
    expected_impact: str
    reasoning: str
    recommended_action: str
    timestamp: datetime
    eta_to_impact: str  # e.g., "5-10 minutes"
    historical_precedent: Optional[str]


@dataclass
class CrossAssetCorrelation:
    """Full correlation analysis for a user's portfolio"""
    user_id: str
    macro_states: Dict[GlobalDriver, MacroDriverState]
    portfolio_exposures: List[CorrelationImpact]
    active_alerts: List[ShadowAlert]
    shadow_beta: float  # Portfolio sensitivity to global macros
    diversification_score: float  # 0-100, how well diversified across macro factors
    last_update: datetime


