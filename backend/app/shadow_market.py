    def calculate_expected_impact(self, symbol: str, driver: GlobalDriver) -> Tuple[float, int]:
        """
        Calculate expected price impact and time to impact.
        
        Returns:
            (expected_impact_pct, lag_minutes)
        """
        if driver not in self.macro_states:
            return 0.0, 0
        
        macro_state = self.macro_states[driver]
        correlation = self.get_correlation_for_stock(symbol, driver)
        
        if abs(correlation) < 0.3:  # Weak correlation
            return 0.0, 0
        
        # Calculate expected impact
        # Formula: correlation * driver_change * sensitivity_factor
        sensitivity = 1.0  # Can be adjusted per stock
        expected_impact = correlation * macro_state.change_pct_1h * sensitivity
        
        # Get typical lag
        lag = self.IMPACT_LAGS.get(driver, 15)
        
        return round(expected_impact, 2), lag
    
    async def analyze_portfolio_exposure(
        self, 
        user_id: str,
        portfolio_positions: List[Dict[str, Any]]
    ) -> CrossAssetCorrelation:
        """
        Analyze portfolio exposure to global macro drivers.
        
        This is the main entry point for shadow market analysis.
        """
        # Ensure we have fresh macro data
        if not self.macro_states or (datetime.now() - self.last_update).seconds > 120:
            await self._update_macro_states()
        
        portfolio_exposures = []
        active_alerts = []
        
        # Analyze each position
        for position in portfolio_positions:
            symbol = position.get('symbol', '')
            if not symbol:
                continue
            
            # Check all drivers
            for driver in GlobalDriver:
                correlation = self.get_correlation_for_stock(symbol, driver)
                
                if abs(correlation) >= 0.5:  # Significant correlation
                    expected_impact, lag = self.calculate_expected_impact(symbol, driver)
                    
                    # Create impact object
                    impact = CorrelationImpact(
                        driver=driver,
                        symbol=symbol,
                        correlation_coefficient=correlation,
                        typical_impact_lag_minutes=lag,
                        expected_price_impact_pct=expected_impact,
                        confidence=min(abs(correlation) * 100 + 20, 95),  # Base confidence on correlation
                        historical_accuracy=0.0,  # Would be calculated from historical data
                        reasoning=self._generate_reasoning(symbol, driver, correlation)
                    )
                    portfolio_exposures.append(impact)
                    
                    # Check for alert conditions
                    alert = self._check_alert_condition(impact, position)
                    if alert:
                        active_alerts.append(alert)
        
        # Calculate portfolio shadow beta
        shadow_beta = self._calculate_shadow_beta(portfolio_positions)
        
        # Calculate diversification score
        diversification_score = self._calculate_diversification_score(portfolio_exposures)
        
        return CrossAssetCorrelation(
            user_id=user_id,
            macro_states=self.macro_states.copy(),
            portfolio_exposures=portfolio_exposures,
            active_alerts=active_alerts,
            shadow_beta=shadow_beta,
            diversification_score=diversification_score,
            last_update=datetime.now()
        )
    
