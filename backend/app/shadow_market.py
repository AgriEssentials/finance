    async def start_monitoring(self):
        """Start the macro monitoring loop"""
        if self._running:
            return
        
        self._running = True
        self._monitor_task = asyncio.create_task(self._monitor_loop())
        print("[SHADOW MARKET] Started global macro monitoring")
    
    async def stop_monitoring(self):
        """Stop monitoring"""
        self._running = False
        if self._monitor_task:
            self._monitor_task.cancel()
            try:
                await self._monitor_task
            except asyncio.CancelledError:
                pass
        print("[SHADOW MARKET] Stopped monitoring")
    
    async def _monitor_loop(self):
        """Main monitoring loop - updates every 60 seconds"""
        while self._running:
            try:
                await self._update_macro_states()
                self.last_update = datetime.now()
            except Exception as e:
                print(f"[SHADOW MARKET] Error in monitor loop: {e}")
            
            await asyncio.sleep(60)  # 60-second update interval
    
    async def _update_macro_states(self):
        """Fetch latest data for all macro drivers"""
        for driver, symbol in self.DRIVER_SYMBOLS.items():
            try:
                # Fetch data using yfinance
                ticker = yf.Ticker(symbol)
                hist = ticker.history(period="2d", interval="1h")
                
                if hist.empty:
                    continue
                
                current = float(hist['Close'].iloc[-1])
                
                # Calculate changes
                if len(hist) >= 2:
                    change_1h = ((current / float(hist['Close'].iloc[-2])) - 1) * 100
                else:
                    change_1h = 0
                
                if len(hist) >= 24:
                    change_24h = ((current / float(hist['Close'].iloc[-24])) - 1) * 100
                else:
                    change_24h = change_1h
                
                # Determine trend
                if change_1h > 0.5:
                    trend = "spiking"
                elif change_1h < -0.5:
                    trend = "dropping"
                else:
                    trend = "stable"
                
                # Calculate volatility (simplified)
                if len(hist) >= 6:
                    recent_volatility = np.std(hist['Close'].iloc[-6:].pct_change().dropna()) * 100
                    if recent_volatility > 1.5:
                        volatility = "high"
                    elif recent_volatility > 0.8:
                        volatility = "normal"
                    else:
                        volatility = "low"
                else:
                    volatility = "normal"
                
                self.macro_states[driver] = MacroDriverState(
                    driver=driver,
                    current_value=current,
                    change_pct_1h=change_1h,
                    change_pct_24h=change_24h,
                    trend=trend,
                    volatility=volatility,
                    last_update=datetime.now()
                )
                
            except Exception as e:
                print(f"[SHADOW MARKET] Error fetching {driver.value}: {e}")
    
