        # Fall back to sector correlation
        sector = self._get_sector_for_stock(symbol)
        if sector and sector in self.SECTOR_CORRELATIONS:
            if driver in self.SECTOR_CORRELATIONS[sector]:
                return self.SECTOR_CORRELATIONS[sector][driver]
        
        return 0.0
    
